// main generates legacy_long_running_operations.go in the merge package from the legacy
// long-running operation list shared with the IPA-132 validation rules.
package main

import (
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"sort"
	"strings"
)

const (
	sourcePath = "../../../../spectral/ipa/rulesets/functions/utils/legacyLroOperationIds.js"
	outputPath = "legacy_long_running_operations.go"

	arrayStart = "export const legacyLroOperationIds = ["
	arrayEnd   = "];"
)

var operationIDLine = regexp.MustCompile(`^ {2}'([a-zA-Z0-9]+)',$`)

func main() {
	if err := run(); err != nil {
		log.Fatal(err)
	}
}

func run() error {
	data, err := os.ReadFile(sourcePath)
	if err != nil {
		return fmt.Errorf("reading %s: %w", sourcePath, err)
	}

	operationIDs, err := extractOperationIDs(string(data))
	if err != nil {
		return err
	}

	sort.Strings(operationIDs)

	var builder strings.Builder
	builder.WriteString("// Code generated by go generate; DO NOT EDIT.\n")
	builder.WriteString("// Source: tools/spectral/ipa/rulesets/functions/utils/legacyLroOperationIds.js\n")
	builder.WriteString("//\n")
	builder.WriteString("// Generated by this command:\n")
	builder.WriteString("//\n")
	builder.WriteString("//\tgo run ./gen\n\n")
	builder.WriteString("package merge\n\n")
	builder.WriteString("// legacyLongRunningOperationIDs is the set of operations returning HTTP 202 that\n")
	builder.WriteString("// predate IPA-132 and do not follow the long-running operation contract.\n")
	builder.WriteString("var legacyLongRunningOperationIDs = map[string]struct{}{\n")
	for _, operationID := range operationIDs {
		fmt.Fprintf(&builder, "%q: {},\n", operationID)
	}
	builder.WriteString("}\n")

	formatted, err := format.Source([]byte(builder.String()))
	if err != nil {
		return fmt.Errorf("formatting %s: %w", outputPath, err)
	}

	//nolint:gosec // The output is a checked-in source file, not a secret.
	if err := os.WriteFile(outputPath, formatted, 0o644); err != nil {
		return fmt.Errorf("writing %s: %w", outputPath, err)
	}

	return nil
}

// extractOperationIDs reads the operationIds from the JavaScript module, accepting only the
// prettier-enforced format of one single-quoted operationId per line, so that any unexpected
// content fails the generation instead of being silently dropped.
func extractOperationIDs(source string) ([]string, error) {
	lines := strings.Split(source, "\n")

	start := -1
	for i, line := range lines {
		if line == arrayStart {
			start = i + 1
			break
		}
	}
	if start == -1 {
		return nil, fmt.Errorf("%s does not declare %q", sourcePath, arrayStart)
	}

	seen := map[string]struct{}{}
	operationIDs := make([]string, 0, len(lines))
	for _, line := range lines[start:] {
		if line == arrayEnd {
			if len(operationIDs) == 0 {
				return nil, fmt.Errorf("%s declares no operationIds", sourcePath)
			}
			return operationIDs, nil
		}

		match := operationIDLine.FindStringSubmatch(line)
		if match == nil {
			return nil, fmt.Errorf("unexpected line %q in %s", line, sourcePath)
		}
		if _, duplicate := seen[match[1]]; duplicate {
			return nil, fmt.Errorf("%s declares %q more than once", sourcePath, match[1])
		}
		seen[match[1]] = struct{}{}
		operationIDs = append(operationIDs, match[1])
	}

	return nil, fmt.Errorf("%s does not terminate the operationIds array with %q", sourcePath, arrayEnd)
}
